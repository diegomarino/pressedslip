#!/usr/bin/env node
/**
 * Generates the playground's emoji assets: a handful of Noto Emoji SVGs
 * (googlefonts/noto-emoji, pinned tag, Apache-2.0) rasterized to grayscale
 * PNG data URIs on a white background, at the printed size (96 px).
 *
 * Why PNG and not SVG: the slip is thresholded to 1 bit, and Noto's flat light
 * fills collapse to nothing at a plain threshold. As PNGs, the image block
 * Floyd–Steinberg-dithers them, which keeps every shape legible.
 *
 * Run: node scripts/docs/generate-emoji-assets.mjs
 * Output: apps/playground/src/variants/assets/emoji.ts (committed).
 */
/** biome-ignore-all lint/suspicious/noConsole: CLI script; stdout is the output channel. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import { decode, encode } from "fast-png";

const NOTO_TAG = "v2.051";
const SIZE_PX = 96;
const EMOJI = {
  toothbrush: "🪥",
  backpack: "🎒",
  balletShoes: "🩰",
  apple: "🍎",
  books: "📚",
  soap: "🧼",
  shoe: "👟",
  soccer: "⚽",
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../../apps/playground/src/variants/assets/emoji.ts");

/** Noto's file name: lowercase hex codepoints joined by `_`, without VS16. */
function notoFilename(emoji) {
  const hex = [...emoji]
    .map((c) => c.codePointAt(0) ?? 0)
    .filter((cp) => cp !== 0xfe0f)
    .map((cp) => cp.toString(16));
  return `emoji_u${hex.join("_")}.svg`;
}

const lines = [];
for (const [name, emoji] of Object.entries(EMOJI)) {
  const url = `https://raw.githubusercontent.com/googlefonts/noto-emoji/${NOTO_TAG}/svg/${notoFilename(emoji)}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const svg = Buffer.from(await res.arrayBuffer());
  const rgba = decode(
    new Resvg(svg, { fitTo: { mode: "width", value: SIZE_PX }, background: "#ffffff" })
      .render()
      .asPng(),
  );
  // One grey channel (Rec. 601 luma): a quarter of the bytes, and all the
  // image block needs, since it binarizes anyway.
  const grey = new Uint8Array(rgba.width * rgba.height);
  for (let i = 0; i < grey.length; i++) {
    const o = i * rgba.channels;
    grey[i] = Math.round(
      0.299 * rgba.data[o] + 0.587 * rgba.data[o + 1] + 0.114 * rgba.data[o + 2],
    );
  }
  const png = encode({ width: rgba.width, height: rgba.height, channels: 1, data: grey });
  lines.push(
    `  /** ${emoji} */\n  ${name}: "data:image/png;base64,${Buffer.from(png).toString("base64")}",`,
  );
  console.log(`[emoji] ${emoji} ${name} — ${png.length} bytes`);
}

writeFileSync(
  OUT,
  `/** @fileoverview Noto Emoji ${NOTO_TAG} rasterized to ${SIZE_PX}px PNGs (Apache-2.0; see README.md). Generated by scripts/docs/generate-emoji-assets.mjs — do not edit. */
export const emojiPng = {
${lines.join("\n")}
} as const;

/** Names of the bundled emoji PNGs. */
export type EmojiName = keyof typeof emojiPng;
`,
);
console.log(`[emoji] wrote ${OUT}`);
